#!/usr/bin/env python3
"""Regenerate the LaTeX sign ledger from the exact integer checker (stdlib only)."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'verify'))
from check_c import check


def ledger():
    data = json.loads((ROOT/'examples/V14_integer.json').read_text(encoding='utf-8'))
    report = check([tuple(int(x) for x in row) for row in data['vertices']])
    lines = ['% Generated by make_ledger.py; integer signs only.',
             r'\begin{table}[ht]', r'\centering\small',
             r'\caption{Facet predicates in cyclic order. Exactly two rows have three plus signs.}\label{tab:faceledger}',
             r'\begin{tabular}{lc@{\qquad\qquad}lc}', r'\toprule',
             r'Oriented facet & Signs & Oriented facet & Signs\\', r'\midrule']
    faces = report['face_checks']
    for left, right in zip(faces[:12], faces[12:]):
        entries = []
        for row in (left, right):
            entries += ['$('+','.join(map(str, row['face']))+')$', r'\texttt{'+row['edge_signs']+'}']
        lines.append(' & '.join(entries)+r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', r'\clearpage', '',
              r'\begin{table}[ht]', r'\centering\footnotesize',
              r'\caption{Edge predicates: two segment signs and twelve global support signs. Only edge $\{6,7\}$ has all positive signs.}\label{tab:edgeledger}',
              r'\begin{tabular}{lcc@{\qquad}lcc}', r'\toprule',
              r'Edge & Segment & Support & Edge & Segment & Support\\', r'\midrule']
    edges = report['edge_checks']
    for left, right in zip(edges[:18], edges[18:]):
        entries = []
        for row in (left, right):
            entries += ['$\{'+','.join(map(str, row['edge']))+r'\}$',
                        r'\texttt{'+row['segment_signs']+'}', r'\texttt{'+row['support_signs']+'}']
        lines.append(' & '.join(entries)+r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    output = ROOT/'paper/latex/equilibrium_ledger.tex'
    output.write_text(ledger(), encoding='utf-8', newline='\n')
    print('Wrote', output.relative_to(ROOT))
